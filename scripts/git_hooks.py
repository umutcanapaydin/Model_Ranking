#!/usr/bin/env python3
"""`make hooks`: git runs `.githooks/pre-push` -- `make gate` -- before every push, beside a hook manager, never over it.

    git_hooks.py install    what `make hooks` runs
    git_hooks.py check      is the first command of a pre-push hook git runs here `.githooks/pre-push`? One line says how

WHY (v7.3; the 2026-10-27 field harvest, 6c). `make hooks` set `core.hooksPath` to `.githooks` whatever was
there. In a repository with husky or pre-commit their hooks stopped running and nothing said so; pre-commit's
own cure, unsetting `core.hooksPath`, then switched the gate off.

Where the pre-push goes, by what the clone holds:
  * nothing else: `core.hooksPath = .githooks`, as before -- the same setting, the same line. So too where the
    setting comes from the developer's global or system git config, which other repositories keep: this clone
    gets its own, with one line saying so, and the global hooks directory is never touched or offered
  * husky (`.husky/`, or husky's own `core.hooksPath`): that setting stays, and `.husky/pre-push`, husky's
    place for one, runs ours
  * hooks in git's own hooks directory (pre-commit's, or any), `core.hooksPath` unset: `pre-push` there runs
    ours -- or, beside pre-commit's own `pre-push`, `pre-push.legacy`, which pre-commit runs first with the
    same refs
It only writes a file that is not there. A hook that is there and does not run ours -- another tool's
`pre-push`, a `core.hooksPath` this clone's config sets to another tool's directory -- is never edited: it stops
(exit 2) with the line to add, and where it goes. A clone already on `.githooks` keeps it, plus one line naming
the hooks that setting leaves unrun; a `core.hooksPath` naming no directory (`/dev/null`) runs no hook, so it is
replaced, as before.

What counts as running ours (review M2): the hook's FIRST command -- its first line that is neither blank nor a
comment -- names `.githooks/pre-push`. A line after another may never run: husky 4's `.git/hooks/pre-push`
sources a script that exits, so a line appended to it named the gate and never ran it. husky 9's runner skips
every hook under `HUSKY=0` (review M1): on that route `check` says so, and session-check FAILs; the Bash guard
refuses `HUSKY=0` on a push. What `.githooks/pre-push` itself runs is not read here (session_check.py and
bootstrap-check C11 say so too).

Exit: install -- 0 done · 1 one step of yours left, named · 2 cannot run, or a hook it may not touch.
      check   -- 0 a pre-push hook git runs has ours first · 1 none does · 2 cannot run.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from session_check import git, main_hooks, resolved  # noqa: E402

OURS = ".githooks/pre-push"
LINE = 'bash .githooks/pre-push "$@"'
SCRIPT = f"#!/bin/sh\n# DevFlow, `make hooks`: make gate before every push -- this repository's {OURS}\n{LINE}\n"
PRE_COMMIT = "# File generated by pre-commit: https://pre-commit.com"
FIRST = f"names {OURS} as its first command"


def text(f: Path) -> str:
    try:
        return f.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def names_ours(f: Path) -> bool:
    """`f` runs ours first: its first line that is neither blank nor a comment names `.githooks/pre-push`. A line
    further down may never run -- after an `exit`, an `exec`, or a sourced script that exits (husky 4's)."""
    first = next((ln.strip() for ln in text(f).splitlines() if ln.strip() and not ln.lstrip().startswith("#")), "")
    return OURS in first


def runs(f: Path) -> bool:
    """git runs `f` as a hook: a file it may execute."""
    return f.is_file() and os.access(f, os.X_OK)


class Clone:
    """What git says about the clone the current directory is in."""

    def __init__(self, top: str, common: str):
        self.top = Path(top).resolve()
        self.common = Path(resolved(common, os.getcwd()) or common)
        self.hp = git("config", "core.hooksPath") or ""
        got = resolved(self.hp, str(self.top)) if self.hp else None
        self.got = Path(got) if got else None
        self.git_hooks = self.common / "hooks"
        # Where the value comes from: `global` or `system` is the developer's own, for every repository (M3). A git
        # too old to say (before 2.26) reads as this clone's.
        shown = git("config", "--show-scope", "--get", "core.hooksPath") or ""
        self.scope = shown.split("\t", 1)[0] if "\t" in shown else ""

    def show(self, p: Path) -> str:
        try:
            return p.resolve().relative_to(self.top).as_posix()
        except ValueError:
            return str(p)

    def on_ours(self) -> bool:
        main = main_hooks()
        return self.got is not None and (self.got == (self.top / ".githooks").resolve()
                                         or (main is not None and self.got == Path(main)))

    def husky(self) -> Path | None:
        """husky's own directory: the one its `core.hooksPath` sits in (husky 9: `<dir>/_` with `h`; 5-8: `<dir>`
        with `_/husky.sh`), else `.husky/` at the top."""
        if self.got is not None and self.got.name == "_" and (self.got / "h").is_file():
            return self.got.parent
        if self.got is not None and (self.got / "_" / "husky.sh").is_file():
            return self.got
        return self.top / ".husky" if (self.top / ".husky").is_dir() else None

    def theirs(self) -> list[str]:
        """The hooks in git's own hooks directory: every executable file that is not a sample."""
        d = self.git_hooks
        return sorted(f.name for f in d.iterdir() if runs(f) and not f.name.endswith(".sample")) if d.is_dir() else []


def clone() -> Clone | None:
    top, common = git("rev-parse", "--show-toplevel"), git("rev-parse", "--git-common-dir")
    return Clone(top, common) if top and common else None


def husky_runner(c: Clone) -> Path | None:
    """husky 9's runner -- the `core.hooksPath` directory `_` with its `h` -- whose stub runs `<home>/pre-push`."""
    d = c.got if c.hp else None
    pre = d / "pre-push" if d is not None else None
    return d if pre is not None and d.name == "_" and (d / "h").is_file() and '/h"' in text(pre) else None


def husky_off(c: Clone) -> bool:
    """`HUSKY=0` in this environment on husky 9's route: its runner then runs no hook at all, ours among them."""
    return os.environ.get("HUSKY") == "0" and husky_runner(c) is not None


def chained(c: Clone) -> str | None:
    """How the pre-push hook git runs here reaches `.githooks/pre-push` first when `core.hooksPath` is not
    `.githooks`, or None. A `core.hooksPath` naming a directory that does not exist runs no hook at all."""
    d = c.got if c.hp else c.git_hooks
    if d is None or not runs(d / "pre-push"):
        return None
    pre = d / "pre-push"
    if names_ours(pre):
        return f"the pre-push hook git runs, `{c.show(pre)}`, {FIRST}"
    legacy = d / "pre-push.legacy"
    if PRE_COMMIT in text(pre) and runs(legacy) and names_ours(legacy):
        return f"pre-commit's `{c.show(pre)}` runs `pre-push.legacy` first, which {FIRST}"
    user = d.parent / "pre-push"
    if husky_runner(c) is not None and names_ours(user) and not husky_off(c):
        return f"husky runs `{c.show(user)}`, which {FIRST}"
    return None


def write(f: Path) -> None:
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(SCRIPT, encoding="utf-8", newline="\n")
    f.chmod(0o755)


def stop(c: Clone, f: Path, why: str) -> int:
    again = (" husky 4 writes this file again at each install: add the line again after one."
             if "husky.sh" in text(f) else "")
    print(f"hooks STOPPED: {why}; make hooks edits no hook it did not write. Add this line to `{c.show(f)}` as its "
          "first command, before anything else runs -- a line after an `exit`, an `exec` or a sourced script that "
          f"exits never runs. It reads the refs git sends on stdin.{again} Then make hooks again:\n  {LINE}")
    return 2


def into_husky(c: Clone, home: Path) -> int:
    user = home / "pre-push"
    if user.exists() and not names_ours(user):
        return stop(c, user, f"`{c.show(user)}` is husky's pre-push, and its first command is not {OURS}")
    done = "kept" if user.exists() else "wrote"
    if done == "wrote":
        write(user)
    what = f"`{c.show(user)}`, which runs {OURS} (make gate)" if done == "wrote" else f"`{c.show(user)}`, which {FIRST}"
    if c.got is not None and (c.got == (home / "_").resolve() or c.got == home.resolve()):
        print(f"hooks: {done} {what}; husky runs it before a push. core.hooksPath stays husky's: {c.hp}")
        return 0
    print(f"hooks: {done} {what}, but husky is not installed in this clone (core.hooksPath: {c.hp or 'unset'}), so "
          "git runs none of its hooks yet. Run husky's install (npm install runs it, or npx husky), then make hooks "
          "again")
    return 1


def into_git_hooks(c: Clone) -> int:
    pre = c.git_hooks / "pre-push"
    if not pre.exists():
        write(pre)
        print(f"hooks: wrote `{c.show(pre)}`, which runs {OURS} (make gate); core.hooksPath stays unset, so the "
              f"hooks in `{c.show(c.git_hooks)}` keep running")
        return 0
    if names_ours(pre):
        print(f"hooks: kept `{c.show(pre)}`, which {FIRST}; core.hooksPath stays unset")
        return 0
    if PRE_COMMIT not in text(pre):
        return stop(c, pre, f"`{c.show(pre)}` is another tool's pre-push, and its first command is not {OURS}")
    legacy = c.git_hooks / "pre-push.legacy"
    if legacy.exists() and not names_ours(legacy):
        return stop(c, legacy, f"`{c.show(legacy)}` runs before pre-commit's pre-push, and its first command is not "
                    f"{OURS}")
    done = "kept" if legacy.exists() else "wrote"
    if done == "wrote":
        write(legacy)
    print(f"hooks: {done} `{c.show(legacy)}`, which runs {OURS} (make gate); pre-commit's `{c.show(pre)}` runs it "
          "first, with the same refs. core.hooksPath stays unset")
    return 0


def install() -> int:
    c = clone()
    if c is None:
        print(f"hooks CANNOT RUN: git cannot name the work tree from {os.getcwd()}: nothing was set")
        return 2
    if not (c.top / OURS).is_file():
        print(f"hooks CANNOT RUN: there is no {OURS} in {c.top}: nothing was set")
        return 2
    home, theirs = c.husky(), c.theirs()
    config = (c.top / ".pre-commit-config.yaml").is_file()
    # A core.hooksPath that names no directory runs no hook at all (`/dev/null`): nothing of anyone's is lost.
    dangling = bool(c.hp) and c.got is None and home is None
    # The developer's own, from the global or system config, for every repository: this clone's setting wins (M3).
    outside = bool(c.hp) and c.scope in ("global", "system") and home is None and not c.on_ours()
    if c.on_ours() or dangling or outside or (not c.hp and home is None and not theirs and not config):
        git("config", "core.hooksPath", ".githooks")
        print(f"core.hooksPath = {git('config', 'core.hooksPath')} -- pre-push now runs make gate")
        if outside:
            print(f"hooks: note -- your {c.scope} git config's core.hooksPath (`{c.hp}`) stays as it is for your other "
                  "repositories; this clone now runs its own .githooks, so the hooks there do not run here")
        elif home is not None:
            print("hooks: note -- core.hooksPath = .githooks leaves husky's hooks unrun. To run them beside the gate: "
                  "husky's install (npm install, or npx husky), then make hooks")
        elif theirs or config:
            what = f"the hooks in `{c.show(c.git_hooks)}` ({', '.join(theirs)})" if theirs else "pre-commit's hooks"
            print(f"hooks: note -- core.hooksPath = .githooks leaves {what} unrun. To run them beside the gate: "
                  "git config --unset core.hooksPath && make hooks")
        return 0
    if home is not None:
        return into_husky(c, home)
    if c.hp and c.got != c.git_hooks.resolve():
        if c.got is not None and runs(c.got / "pre-push") and names_ours(c.got / "pre-push"):
            print(f"hooks: kept `{c.show(c.got / 'pre-push')}`, which {FIRST}; core.hooksPath stays {c.hp}")
            return 0
        return stop(c, c.got / "pre-push",
                    f"core.hooksPath is `{c.hp}`, which something else set here, and DevFlow leaves it as it is")
    return into_git_hooks(c)


def check() -> int:
    c = clone()
    if c is None:
        print(f"hooks CANNOT RUN: git cannot name the work tree from {os.getcwd()}")
        return 2
    if c.on_ours():
        print("hooks: core.hooksPath resolves to .githooks")
        return 0
    how = chained(c)
    if how:
        print(f"hooks: {how}")
        return 0
    if husky_off(c):
        print("hooks: HUSKY=0 is set, so husky's runner runs no hook here, the pre-push gate among them")
        return 1
    print(f"hooks: no pre-push hook git runs here has {OURS} first (core.hooksPath: {c.hp or 'unset'}) -- run make hooks")
    return 1


if __name__ == "__main__":
    if sys.argv[1:] == ["install"]:
        sys.exit(install())
    if sys.argv[1:] == ["check"]:
        sys.exit(check())
    print("usage: git_hooks.py install | check")
    sys.exit(2)
