#!/usr/bin/env python3
"""`make hooks` puts the pre-push gate beside husky or pre-commit: their hooks keep running, and the gate runs too.

WHY (the 2026-10-27 field harvest, 6c; v7.3 A35). `make hooks` set `core.hooksPath` to `.githooks` whatever was
there. In a repository with husky or pre-commit, their hooks stopped running and nothing said so; pre-commit's own
cure, unsetting `core.hooksPath`, then turned the gate off. `scripts/git_hooks.py` now adds DevFlow's pre-push
where the manager runs one -- husky's `.husky/pre-push`, git's own `.git/hooks/pre-push`, or `pre-push.legacy`
beside pre-commit's -- and edits no hook it did not write. `session-check` and bootstrap-check C11 accept a
pre-push hook git runs that names `.githooks/pre-push`; a clone with no other hooks keeps `.githooks`, byte for byte.

Each case builds a throwaway repository: a stand-in `.githooks/pre-push` records the refs git sends it, and the
manager's own hooks record that they ran. The husky layouts are husky 9's (`.husky/_/h` and its stubs) and 5-8's; the
pre-commit hooks are stand-ins with pre-commit's header, since neither tool is installed here. The fixtures run side
by side, each in its own directory; their cases are graded in the order written (v7.3.1, gate speed).

Exit: 0 every case behaves - 1 one does not - 2 git or bash not runnable here.
"""
