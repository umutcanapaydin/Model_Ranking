def write(path: pathlib.Path, text: str, mode: int = 0o755) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    path.chmod(mode)


class Repo:
    """A throwaway clone with a bare origin: `.githooks/pre-push` is the gate's stand-in."""

    def __init__(self, base: pathlib.Path, name: str):
        self.dir = base / name
        self.marks = base / f"{name}-marks"
        self.marks.mkdir(parents=True)
        (base / "empty-gitconfig").touch()
        self.env = scrubbed_env({"MARKS": str(self.marks), "GIT_CONFIG_NOSYSTEM": "1", "HOME": str(base),
                                 "GIT_CONFIG_GLOBAL": str(base / "empty-gitconfig")})
        self.env.pop("XDG_CONFIG_HOME", None)
        self.env.pop("GITHUB_ACTIONS", None)
        self.dir.mkdir()
        self.git("init", "-q", "-b", "main")
        for key, value in QUIET_GIT + (("user.name", "f"), ("user.email", "f@x")):
            self.git("config", key, value)
        write(self.dir / ".githooks" / "pre-push", GATE)
        write(self.dir / "README.md", "a repository\n", 0o644)
        self.git("add", "-A")
        self.git("commit", "-qm", "base")
        self.git("init", "-q", "--bare", str(base / f"{name}-origin.git"))
        self.git("remote", "add", "origin", str(base / f"{name}-origin.git"))
        (self.dir / ".git" / "devflow-sessions").mkdir()
        (self.dir / ".git" / "devflow-sessions" / SID).write_text("", encoding="utf-8")

    def git(self, *args: str, check: bool = True) -> subprocess.CompletedProcess:
        return subprocess.run(["git", *args], cwd=self.dir, capture_output=True, encoding="utf-8",
                              errors="replace", env=self.env, check=check)

    def run(self, *args: str, sid: bool = False, **extra: str) -> tuple[int, str]:
        env = dict(self.env, **({"CLAUDE_CODE_SESSION_ID": SID} if sid else {}), **extra)
        r = subprocess.run(list(args), cwd=self.dir, capture_output=True, encoding="utf-8", errors="replace", env=env)
        return r.returncode, r.stdout + r.stderr

    def hooks(self, cmd: str = "install", **extra: str) -> tuple[int, str]:
        return self.run(sys.executable, str(SCRIPT), cmd, **extra)

    def hooks_path(self) -> str:
        return self.git("config", "core.hooksPath", check=False).stdout.strip()

    def commit(self) -> None:
        (self.dir / "README.md").write_text(self.read("README.md") + "a line\n", encoding="utf-8")
        self.git("commit", "-qam", "a change")

    def push(self, **extra: str) -> tuple[int, str]:
        (self.marks / "gate").unlink(missing_ok=True)
        r = subprocess.run(["git", "push", "-q", "origin", "HEAD:refs/heads/work"], cwd=self.dir, capture_output=True,
                           encoding="utf-8", errors="replace", env=dict(self.env, **extra))
        return r.returncode, r.stdout + r.stderr

    def read(self, rel: str) -> str:
        p = self.dir / rel
        return p.read_text(encoding="utf-8") if p.is_file() else ""

    def mark(self, name: str) -> str:
        p = self.marks / name
        return p.read_text(encoding="utf-8") if p.is_file() else ""

    def head(self) -> str:
        return self.git("rev-parse", "HEAD").stdout.strip()


def scripts(d: pathlib.Path) -> None:
    """The scripts `make hooks` and bootstrap-check C11 run, beside the fixture's own (one missing is not copied)."""
    (d / "scripts").mkdir(exist_ok=True)
    for name in ("git_hooks.py", "session_check.py", "brief_fields.py"):
        if (ROOT / "scripts" / name).is_file():
            shutil.copy2(ROOT / "scripts" / name, d / "scripts" / name)


def husky(r: Repo, installed: bool = True) -> None:
    """husky 9's layout: `core.hooksPath = .husky/_`, a stub per hook there, the user's hooks one level up."""
    write(r.dir / ".husky" / "pre-commit", 'echo husky > "$MARKS/husky-pre-commit"\n', 0o644)
    if installed:
        write(r.dir / ".husky" / "_" / "h", H)
        write(r.dir / ".husky" / "_" / ".gitignore", "*", 0o644)
        for hook in ("pre-commit", "commit-msg", "pre-push"):
            write(r.dir / ".husky" / "_" / hook, STUB)
        r.git("config", "core.hooksPath", ".husky/_")


def husky58(r: Repo, where: str) -> None:
    """husky 5-8's layout: `core.hooksPath = <where>`, `<where>/_/husky.sh`, the user's hooks in `<where>` itself."""
    write(r.dir / where / "_" / "husky.sh", '[ "${HUSKY-}" = "0" ] && exit 0\n', 0o644)
    write(r.dir / where / "pre-commit", '#!/bin/sh\n. "$(dirname "$0")/_/husky.sh"\necho husky > "$MARKS/husky-pre-commit"\n')
    r.git("config", "core.hooksPath", where)


